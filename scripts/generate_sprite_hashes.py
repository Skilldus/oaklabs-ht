"""Generate the sprite integrity manifest from the pinned PokeAPI checkout.

Usage: python scripts/generate_sprite_hashes.py PATH_TO_SPRITES_CHECKOUT
The checkout must be at the revision pinned in sprites.ts.
"""

import hashlib
import subprocess
import sys
from pathlib import Path


REVISION = "c0542f7c51215d9672439012838c99f520596cbd"
BLACK_WHITE = {992, 994, 995, 1006, 1008, 1024}
STATIC = {990, 991, 993, 1010, 1017, 1022, 1023, 1025}
COUNT = 1025
OUTPUT = Path(__file__).resolve().parents[1] / "src/oaklabs-companions/sprite-hashes.ts"


def main() -> None:
    source = Path(sys.argv[1]).resolve()
    actual = subprocess.check_output(
        ["git", "-C", str(source), "rev-parse", "HEAD"], text=True
    ).strip()
    if actual != REVISION:
        raise SystemExit(f"Expected {REVISION}, got {actual}")
    root = source / "sprites/pokemon"
    tree = subprocess.check_output(
        ["git", "-C", str(source), "ls-tree", "-r", "HEAD", "sprites/pokemon"], text=True
    )
    blobs = {}
    for line in tree.splitlines():
        metadata, path = line.split("\t", 1)
        blobs[path] = metadata.split()[2]
    entries = []
    for pokemon in range(1, COUNT + 1):
        paths = [(f"{pokemon}.png", root / f"{pokemon}.png")]
        if pokemon not in STATIC:
            gif = (
                root / "versions/generation-v/black-white/animated" / f"{pokemon}.gif"
                if pokemon in BLACK_WHITE
                else root / "other/showdown" / f"{pokemon}.gif"
            )
            paths.append((f"{pokemon}.gif", gif))
        for key, path in paths:
            if path.is_file():
                data = path.read_bytes()
                blob = hashlib.sha1(f"blob {len(data)}\0".encode() + data).hexdigest()
                relative = path.relative_to(source).as_posix()
                if blobs.get(relative) != blob:
                    raise SystemExit(f"File differs from pinned commit: {relative}")
                entries.append((key, hashlib.sha256(data).hexdigest()))
    expected_count = COUNT * 2 - len(STATIC)
    if len(entries) != expected_count:
        raise SystemExit(f"Expected {expected_count} sprites, found {len(entries)}")
    lines = [
        "// Generated by scripts/generate_sprite_hashes.py from PokeAPI/sprites",
        f"// revision {REVISION}. Do not edit by hand.",
        "export const SPRITE_HASHES: Readonly<Record<string, string>> = {",
        *(f'  "{key}": "{digest}",' for key, digest in entries),
        "};",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(entries)} hashes to {OUTPUT}")


if __name__ == "__main__":
    main()
